/// A compact reading order for image answers; never add missing facts to fill it.
class ImageReplyFormat {
  static const instructions = '''图片回复排版：
先一句话直接概括已确认的结论，不寒暄，不说正在分析，不整段照抄原文。
段落之间空一行；标题用“### 标题”，条目用“- 字段：内容”，实付金额和关键结论用 **加粗**。不用表格、代码块、JSON或嵌套列表。
账单按需分为“交易信息”“优惠信息”“待确认”：商户、实付、时间、状态逐行列出；红包、折扣、抵扣单列优惠，不当成支出。实付不清晰写“实付金额：未能确认”，不得用优惠替代或推算。
多笔交易按“第1笔 · 对方”等逐笔分组，不串金额与日期；金额、币种、方向、完成状态未全部明确时不算合计。
普通图片用“关键信息”等短分组；人物与号码一一对应。不为凑格式补造字段；没有优惠或疑点就省略分组。最后至多问一个具体问题；是否保存和提醒以真实回执为准。
''';
}
